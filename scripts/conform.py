"""Check our code against the core's contracts (causal_core.contracts) in one command (~2-4 min).

    python -I scripts/conform.py            # schema diff + conformance tests + 106 samples + sample checks
    python -I scripts/conform.py --diff     # only the field-by-field diff: Contracts/ (old copy) vs causal_core.contracts

Writes docs/CONFORMANCE_REPORT.md. Exit code 1 if any step fails. Rerun after every contracts update from the core team.
"""
import importlib
import inspect
import pathlib
import subprocess
import sys
import time

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
MODULES = ("capabilities", "common", "evidence", "graph", "observations", "studies", "tasks", "variables", "ports")


def fields(mod_name: str) -> dict:
    out = {}
    for m in MODULES:
        try:
            mod = importlib.import_module(f"{mod_name}.{m}")
        except ModuleNotFoundError:
            continue
        for name, cls in inspect.getmembers(mod, inspect.isclass):
            if cls.__module__ == mod.__name__ and hasattr(cls, "model_fields"):
                out[f"{m}.{name}"] = {f: ("required" if i.is_required() else "optional", str(i.annotation).replace("typing.", "").replace("causal_core.contracts.", "").replace("Contracts.", "")[:70])
                                      for f, i in cls.model_fields.items()}
    return out


def schema_diff() -> list[str]:
    old, new = fields("Contracts"), fields("causal_core.contracts")
    L = ["| Contract | Change |", "|---|---|"]
    for k in sorted(set(old) | set(new)):
        if k not in new:
            L.append(f"| `{k}` | removed in the core's contracts |")
        elif k not in old:
            L.append(f"| `{k}` | new in the core's contracts ({len(new[k])} fields) |")
        else:
            for f in sorted(set(old[k]) | set(new[k])):
                a, b = old[k].get(f), new[k].get(f)
                if a != b:
                    what = "added" if a is None else "removed" if b is None else "changed"
                    L.append(f"| `{k}.{f}` | {what}: {a or '—'} → {b or '—'} |")
    return L


STEPS = [
    ("contract conformance tests (ports, roles, taxonomy, import boundary)",
     [sys.executable, "-m", "pytest", "-q", "-o", "addopts=", "tests/test_contracts_conformance.py", "tests/test_variable_catalog.py"]),
    ("emulator, closed loop and storefront tests", [sys.executable, "-m", "pytest", "-q", "-o", "addopts=", "tests/test_m1_m2_emulator.py",
                                                     "tests/test_m3_mvs.py", "tests/test_m4_m5_storefront.py"]),
    ("regenerate 106 contract samples", [sys.executable, "-I", "scripts/stitch_samples.py", "--no-repeat"]),
    ("re-check written samples", [sys.executable, "-m", "pytest", "-q", "-o", "addopts=", "tests/test_stitch_samples.py"]),
    ("the core's own parser accepts every sample (causal_core.api.parse_observation)", [sys.executable, "-I", "-c",
     "import sys,json,pathlib; sys.path.insert(0,'.'); from causal_core.api import parse_observation, parse_definition; "
     "fs=sorted((pathlib.Path.home()/'data/mkt/stitch/samples').glob('*.json')); n=0\n"
     "for f in fs:\n d=json.loads(f.read_text()); de=parse_definition(d['definition'])\n for s in d['samples']: parse_observation(s['observation'], de); n+=1\n"
     "print(f'{n} observations from {len(fs)} variables accepted')"]),
]


def main() -> int:
    diff = schema_diff()
    L = ["# Conformance report: our code vs `causal_core.contracts` (generated by `scripts/conform.py`)", "",
         "## Contract changes since the `Contracts/` copy", "", *diff, ""]
    if "--diff" in sys.argv:
        print("\n".join(diff))
        return 0
    ok_all = True
    L += ["## Checks", "", "| Step | Result | Time |", "|---|---|---|"]
    for name, cmd in STEPS:
        t = time.perf_counter()
        p = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
        ok = p.returncode == 0
        ok_all &= ok
        tail = [l for l in (p.stdout + p.stderr).strip().splitlines() if l.strip()][-1:] or [""]
        L.append(f"| {name} | {'PASS' if ok else 'FAIL'}: {tail[0][:140]} | {time.perf_counter() - t:.0f} s |")
        print(f"{'PASS' if ok else 'FAIL'}  {name}  ({time.perf_counter() - t:.0f} s)  {tail[0][:160]}")
        if not ok:
            print("\n".join((p.stdout + p.stderr).strip().splitlines()[-25:]))
    (ROOT / "docs/CONFORMANCE_REPORT.md").write_text("\n".join(L) + "\n")
    print(f"{len(diff) - 2} contract differences; report: docs/CONFORMANCE_REPORT.md")
    return 0 if ok_all else 1


if __name__ == "__main__":
    sys.exit(main())
