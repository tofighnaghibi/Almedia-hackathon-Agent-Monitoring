"""Stitch stage (ARCHITECTURE.md §7.5-7.6): turn every dataset into transport cards / bridge tables.

    python -I scripts/stitch.py list                       # the plan: one row per stitching-table entry
    python -I scripts/stitch.py run [ROW ...] [--workers 4] [--force]
    python -I scripts/stitch.py report                     # rewrite docs/stitch/STITCH_REPORT.md + diagram from the manifest

Rows run in parallel processes, heaviest first; each row is cached by (fitter source + input file fingerprints),
so a re-run only redoes rows whose code or data changed. A failing row is recorded as 'failed' and the rest continue.
"""
import argparse
import hashlib
import inspect
import json
import pathlib
import subprocess
import sys
import time
import traceback
from concurrent.futures import ProcessPoolExecutor, as_completed
from datetime import datetime, timezone

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from mkt.stitch import fitters  # noqa: E402
from mkt.stitch.plan import BY_ID, PLAN  # noqa: E402

DOCS = ROOT / "docs/stitch"
CARDS = DOCS / "cards"
MANIFEST = DOCS / "manifest.json"
HEAVY = ["L4-sessions", "L4-recs", "L1-products", "L2-search", "L2-offers", "L4-exposure", "L4-ads", "L7-experiments", "L2-stock",
         "L1-devices", "L4-funnel", "L9-logging", "L5-returns", "L2-prices", "L4-repeat", "L6-fraud"]


def fingerprint(sources) -> dict:
    fp = {}
    for s in sources:
        for f in sorted((fitters.RAW / s).rglob("*")):
            if f.is_file() and f.suffix not in (".zip", ".md", ".txt") and ".git" not in f.parts:
                st = f.stat()
                fp[str(f.relative_to(fitters.RAW))] = [st.st_size, int(st.st_mtime)]
    return fp


def cache_key(e) -> tuple[str, dict]:
    fp = fingerprint(e.sources)
    src = inspect.getsource(getattr(fitters, e.fitter))
    if e.fitter in ("devices", "sessions", "funnel", "exposure"):
        from mkt.stitch import cards
        src += inspect.getsource(cards)
    return hashlib.sha256(json.dumps([src, fp], sort_keys=True).encode()).hexdigest()[:16], fp


def status(body) -> str:
    if body.get("status_override"):
        return body["status_override"]
    checks = body["heldout"]
    ok = all(h["pass"] for h in checks)
    if body["target"]:
        return "supported (fitted on Olist; held-out stable)" if ok else "partially supported (fitted on Olist; drifts between halves)"
    return "partially supported (transferred; held-out stable)" if ok else "unsupported transfer (held-out unstable; sensitivity = both halves)"


def run_one(row_id: str, threads: int) -> dict:
    e = BY_ID[row_id]
    t = time.perf_counter()
    try:
        body = getattr(fitters, e.fitter)(fitters.db(threads))
        card = {"status": status(body), **body}
    except Exception as ex:                                       # record and continue
        card = {"status": "failed", "error": f"{type(ex).__name__}: {ex}", "trace": traceback.format_exc()[-2000:]}
    card.update({"id": e.id, "layer": e.layer, "data_type": e.data_type, "method": e.method, "sources": list(e.sources),
                 "consumed_by": e.consumed_by, "heldout_plan": e.heldout, "seconds": round(time.perf_counter() - t, 1)})
    return card


def write_report(man: dict) -> None:
    rows = [man["cards"][e.id] for e in PLAN if e.id in man["cards"]]
    by = {}
    for r in rows:
        by[r["status"].split(" (")[0]] = by.get(r["status"].split(" (")[0], 0) + 1
    L = ["# Stitch report (generated by `scripts/stitch.py`)", "",
         f"Run {man['run_at']} · wall time {man['wall_seconds']} s · workers {man['workers']} · rows {len(rows)}/{len(PLAN)} · "
         + " · ".join(f"{k}: {v}" for k, v in sorted(by.items())), "",
         "| Row | Data type | Sources | Status | Held-out | Used by simulator | s |", "|---|---|---|---|---|---|---|"]
    for r in rows:
        h = "; ".join(f"{x['name']}: {'pass' if x['pass'] else 'FAIL'}" for x in r.get("heldout", [])) or "—"
        L.append(f"| {r['id']} | {r['data_type']} | {', '.join(r['sources']) or '—'} | {r['status']}"
                 f"{' — ' + r['error'] if r['status'] == 'failed' else ''} | {h} | {r['consumed_by'] or 'not yet'} | {r['seconds']} |")
    L += ["", "Cards: `docs/stitch/cards/<row>.json` · bridge tables: `~/data/mkt/stitch/bridges/` · cache: `~/data/mkt/stitch/cache/`"]
    (DOCS / "STITCH_REPORT.md").write_text("\n".join(L) + "\n")
    subprocess.run([sys.executable, "-I", str(ROOT / "docs/tools/make_stitch_pipeline_excalidraw.py")], check=False, capture_output=True)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["list", "run", "report"])
    ap.add_argument("rows", nargs="*")
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args()
    if a.cmd == "list":
        for e in PLAN:
            print(f"{e.id:16} {e.layer:3} {e.data_type:40} {e.method:24} {','.join(e.sources):32} {e.consumed_by or '-'}")
        return 0
    CARDS.mkdir(parents=True, exist_ok=True)
    man = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {"cards": {}}
    if a.cmd == "report":
        write_report(man)
        print(DOCS / "STITCH_REPORT.md")
        return 0
    todo = [BY_ID[r] for r in a.rows] if a.rows else PLAN
    keys = {e.id: cache_key(e) for e in todo}
    run = [e for e in todo if a.force or man["cards"].get(e.id, {}).get("cache_key") != keys[e.id][0]
           or man["cards"][e.id]["status"] == "failed"]
    run.sort(key=lambda e: HEAVY.index(e.id) if e.id in HEAVY else len(HEAVY))
    print(f"{len(todo) - len(run)} cached, {len(run)} to run, {a.workers} workers")
    t0 = time.perf_counter()
    threads = max(1, 8 // a.workers)
    with ProcessPoolExecutor(a.workers) as ex:
        futs = {ex.submit(run_one, e.id, threads): e.id for e in run}
        for f in as_completed(futs):
            card = f.result()
            card["cache_key"], card["inputs"] = keys[card["id"]]
            (CARDS / f"{card['id']}.json").write_text(json.dumps(card, indent=1, default=str))
            man["cards"][card["id"]] = {k: card[k] for k in ("id", "layer", "data_type", "sources", "status", "heldout", "consumed_by",
                                                             "seconds", "cache_key") if k in card} | ({"error": card["error"]} if "error" in card else {})
            print(f"{card['seconds']:7.1f}s  {card['id']:16} {card['status'][:70]}" + (f"  !! {card.get('error', '')[:120]}" if card["status"] == "failed" else ""),
                  flush=True)
    man.update({"run_at": datetime.now(timezone.utc).isoformat(timespec="seconds"), "wall_seconds": round(time.perf_counter() - t0, 1),
                "workers": a.workers})
    MANIFEST.write_text(json.dumps(man, indent=1, default=str))
    write_report(man)
    failed = [k for k, v in man["cards"].items() if v["status"] == "failed"]
    print(f"done in {man['wall_seconds']} s; failed: {failed or 'none'}; report: {DOCS / 'STITCH_REPORT.md'}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
