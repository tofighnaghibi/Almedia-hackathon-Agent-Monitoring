"""Internal engine types (formerly mkt/v3.py). NOT the core-facing contracts: those are Contracts/ (schema 2.0),
served through mkt/core_port.py. Classes whose names clashed with Contracts carry an "Engine" prefix.

Original note: input-layer contracts in the causal core v3's own vocabulary (ARCHITECTURE.md §9.0).

Names and responsibilities follow `causal_core_v3_domain_agnostic_architecture.excalidraw`
(Subsystem 2, v3.0). Where that diagram names a contract but not its fields, fields here are
PROVISIONAL (marked in each docstring) and must be aligned with the v3 owner before integration.

Rules carried over from the v3 diagram:
  * frozen contracts, per-type validators, explicit scopes and provenance, no silent coercion
  * typed payloads: sample / aggregate / series / event sequence / panel / assignment
  * a source without experiments can still be investigated; unsupported fields are NOT invented
  * unsupported shape or request => explicit refusal with a failure code
"""
from __future__ import annotations

from datetime import datetime
from enum import Enum
from typing import Any, Literal, Protocol, Union

from pydantic import BaseModel, ConfigDict, Field, model_validator

V3_SCHEMA = "mkt-input.v3.provisional-1"
# SUPERSEDED for anything the core sees (22 Nov 2026): Contracts/ (schema 2.0) via mkt/core_port.py.
# These types remain only as the internal engine's request/response format.


class _Frozen(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")


# ------------------------------------------------------------------ variables
class VariableKind(str, Enum):
    STATE = "state"
    CONTINUOUS = "continuous"
    CATEGORICAL = "categorical"
    EVENT = "event"
    ASSIGNMENT = "assignment"
    METRIC = "metric"


class EngineVariable(_Frozen):
    """v3: EngineVariable(id, kind, value_schema). Extra fields (unit, scope, description) provisional."""
    id: str
    kind: VariableKind
    value_schema: dict[str, str]                 # field -> type, e.g. {"amount": "float[BRL]"}
    unit: str | None = None
    scope: str                                    # population the variable is defined over, e.g. "orders"
    description: str = ""


class EngineMetric(EngineVariable):
    """v3: EngineMetric(formula, grain, units): a specialised variable."""
    kind: Literal[VariableKind.METRIC] = VariableKind.METRIC
    formula: str                                  # e.g. "count(order_placed)", "count(delivered[days_late>0]) / count(delivered)"
    grain: list[str]                              # e.g. ["week"], ["day", "region"]
    population: str
    empirical_identities: list[str] = []          # accounting identities: never "discovered" as causal


# ------------------------------------------------------------------ provenance & scope
class OriginClass(str, Enum):
    REAL = "real"                 # recorded observation of the real world
    DERIVED = "derived"           # deterministic transform of real observations
    TRANSPORTED = "transported"   # parameter learned elsewhere and applied here (needs a transport card)
    BRIDGED = "bridged"           # real record attached to a synthetic entity (not an identity claim)
    SYNTHETIC = "synthetic"       # generated by a simulator
    PREDICTION = "prediction"     # model forecast; never certifies anything


class EnvironmentKind(str, Enum):
    PRODUCTION = "production"
    REAL_REPLAY = "real_replay"
    STAGING = "staging"
    EMULATOR = "emulator"


class EngineScope(_Frozen):
    """v3 names 'environment' on evidence; fields provisional."""
    id: str
    kind: EnvironmentKind
    data_cut: datetime | None = None
    mechanism_versions: dict[str, str] = {}
    assumptions: list[str] = []                   # e.g. how available_at was set


class LineageRoot(_Frozen):
    source: str                                   # adapter namespace, e.g. "olist"
    source_version: str                           # registry manifest version
    files: dict[str, str]                         # file -> sha256
    table: str | None = None


class EngineLineage(_Frozen):
    roots: list[LineageRoot]
    transformations: list[str] = []               # e.g. ["adapter olist v<hash>", "metric orders_count"]
    trained_through: datetime | None = None       # for anything fitted (ARCHITECTURE §7.6)
    transport_card: str | None = None             # required when origin is TRANSPORTED


class EngineEvidence(_Frozen):
    """v3: immutable evidence with lineage in the EvidenceLedger; fields provisional."""
    id: str
    origin: OriginClass
    environment_id: str
    lineage: EngineLineage

    @model_validator(mode="after")
    def _transport_needs_card(self):
        if self.origin == OriginClass.TRANSPORTED and not self.lineage.transport_card:
            raise ValueError("transported evidence must reference a transport card")
        return self


# ------------------------------------------------------------------ observations
PayloadShape = Literal["sample", "aggregate", "series", "event_sequence", "panel", "assignment"]


class EngineObservation(_Frozen):
    """v3: typed payload + lineage, environment, revisions, observation mechanism and missingness."""
    id: str
    variable_id: str
    shape: PayloadShape
    payload: Any                                  # shape-specific; see port docstrings
    window_start: datetime | None = None
    window_end: datetime | None = None
    available_at: datetime                        # earliest time a reader could have known this
    population: str
    revision: int = 0
    supersedes: str | None = None
    observation_mechanism: str                    # how it was measured / logged
    missingness: str                              # what is known to be missing and why
    quality_flags: list[str] = []
    evidence_id: str


# ------------------------------------------------------------------ studies & interventions
class EngineStudyDesign(_Frozen):
    """v3: randomized or observational; experimentation is one evidence design, not a default."""
    id: str
    design: Literal["randomized", "observational"]
    unit: str
    assignment_policy: str
    outcome_variable: str
    target_estimand: str
    propensity_known: bool
    compliance_observed: bool


class InterventionSpec(_Frozen):
    """v3: separately typed. Proposed intervention; execution happens elsewhere."""
    id: str
    target: str
    scope: str
    operator: Literal["set", "shift", "scale", "replace", "disable"]
    value: float | str
    window_start: datetime
    window_end: datetime
    requested_by: str
    authorization: str | None = None


class InterventionEvent(_Frozen):
    spec_id: str
    status: Literal["accepted", "rejected", "executed", "aborted"]
    at: datetime
    failure_code: str | None = None
    reason: str = ""


class FailureCode(str, Enum):
    UNSUPPORTED_SHAPE = "UNSUPPORTED_SHAPE"
    UNSUPPORTED_REQUEST = "UNSUPPORTED_REQUEST"
    UNKNOWN_VARIABLE = "UNKNOWN_VARIABLE"
    NO_INTERVENTIONS_IN_ENVIRONMENT = "NO_INTERVENTIONS_IN_ENVIRONMENT"
    NO_STUDIES_IN_SOURCE = "NO_STUDIES_IN_SOURCE"
    BUDGET_EXCEEDED = "BUDGET_EXCEEDED"


class CapabilitySpec(_Frozen):
    """v3: accepted shapes, required metadata, assumptions, cost, failure codes."""
    source_id: str
    environment_id: str
    variables: list[str]
    accepted_shapes: dict[str, list[PayloadShape]]     # variable -> shapes it can be served in
    supported_requests: list[str]
    required_metadata: list[str]
    assumptions: list[str]
    cost: dict[str, float]                             # e.g. {"rows_per_query_max": 5e6}
    failure_codes: list[FailureCode]


class EvidenceRequest(_Frozen):
    """Typed request to the EngineAccessPort (fields provisional)."""
    variable_id: str
    shape: PayloadShape
    as_of: datetime                                    # nothing with available_at > as_of is returned
    window_start: datetime | None = None
    window_end: datetime | None = None
    grain: str | None = None                           # e.g. "week" for series
    filters: dict[str, str] = {}


class Refusal(_Frozen):
    code: FailureCode
    reason: str


class EvidenceResult(_Frozen):
    observations: list[EngineObservation]
    evidence: list[EngineEvidence]


class EngineAccessPort(Protocol):
    """v3 outbound port: read-only, budgeted, typed."""
    def capabilities(self) -> CapabilitySpec: ...
    def variables(self) -> list[EngineVariable]: ...              # incl. MetricDefinitions with empirical identities
    def query(self, request: EvidenceRequest) -> Union[EvidenceResult, Refusal]: ...
